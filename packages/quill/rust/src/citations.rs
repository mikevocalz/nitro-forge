//! Citations, bibliography sources, and bibliography fields (P12 slice 8,
//! third part — the last Quill backlog slice).
//!
//! Model decision — two document-level collections plus one positioned
//! field block, deliberately NOT footnotes with extra steps:
//!
//! - `CitationSource` is a bibliography record `{id, author, title, ...}`
//!   stored in a document-level `sources` list. There is no inline
//!   bibliography text: sources exist only as data.
//! - `Citation` is `{id, at, source, locator?}` — a single live
//!   `{block,offset}` reference anchor (the `CommentAnchor` shape
//!   footnotes reuse) naming a `sources[].id`, plus an optional free-text
//!   `locator` ("p. 42", "§3", …). The anchor is bookmark right gravity,
//!   never drops (delete clamps to the deletion start), and re-maps
//!   through every position-moving op through the same machinery
//!   comments/revisions/footnotes use. There is no rendered "[1]" mark in
//!   the block stream — citation marks are consumer-rendered, same as
//!   footnote bodies.
//! - A bibliography is a `kind:"bibliography"` field block carrying
//!   `BibliographyField {sort, entries}` — the Word-field-cache pattern
//!   `kind:"toc"` established: `entries` is a cached `[{source,text}]
//!   scan snapshot regenerated by `insertBibliography`/`updateBibliography`/
//!   `refreshBibliography`; `listBibliography` is the always-live read.
//!   Entries reference source ids, never block indices, so block edits
//!   need no entry remap — only the field-block guards apply.
//!
//! Honest subset and deferrals: no CSL processor or citation-style
//! language (the `sort` option is the only style surface — `"alpha"`
//! orders entries by formatted text, `"citation"` by first-citation
//! document order); no DOI/URL fetching or metadata lookup (sources are
//! caller-supplied data only); no Word `CITATION`/`BIBLIOGRAPHY` field
//! or `w:fldSimple` interop (`exportDocx` rejects bibliography blocks
//! like toc fields); no uncited-source inclusion toggle (a bibliography
//! lists exactly the cited sources); no ibid/ibid.-style suppression,
//! no multi-key sorting, and no per-citation rendered-form override —
//! `format_source` is one deterministic plain-text rendering shared by
//! every entry. `year` and the optional metadata fields are strings
//! (years may be ranges or "n.d."), never parsed.
//!
//! Referential integrity: `addCitation`/`updateCitation` require `source`
//! to name an existing source, and restore validates the same — a
//! citation can never dangle. `removeSource` cascades: deleting a source
//! also deletes every citation that referenced it (one undo entry), the
//! Word "delete source" gesture; bibliography caches simply go stale
//! until the next refresh, exactly like toc entries on heading edits.
//!
//! Snapshots ride the schema:3 `deny_unknown_fields` document as
//! optional `citations`/`sources` keys — schema:3-era readers fail
//! closed on them, so no schema bump (same precedent as
//! comments/sections/revisions/footnotes). Bibliography blocks need no
//! bump either: the `"bibliography"` `BlockKind` variant fails pre-feature
//! readers closed via serde, the `"table"`/`"toc"` precedent. Schema:2
//! and legacy payloads carrying either key reject rather than silently
//! dropping.

use super::comments::CommentAnchor;
use super::*;
use serde::{Deserialize, Serialize};

/// Bound on stored bibliography sources (mirrors the footnote budget).
pub const SOURCES_MAX: usize = 1024;
/// Bound on stored citations.
pub const CITATIONS_MAX: usize = 2048;
/// Every source text field (author/title/metadata) is at most this many
/// chars; author and title must additionally be non-blank.
const SOURCE_TEXT_MAX: usize = 512;
/// Citation locators ("p. 42", "§3") are short free text.
const LOCATOR_MAX: usize = 128;
/// Bound on bibliography field blocks per document (mirrors TOC_FIELDS_MAX).
pub const BIBLIOGRAPHY_FIELDS_MAX: usize = 64;
/// Cached bibliography entry text is the formatted source line.
pub const BIBLIO_TEXT_MAX: usize = 8192;

/// One bibliography source record. `author` and `title` are required
/// non-blank text; every other field is optional metadata kept as raw
/// strings — the engine never parses years, DOIs, or URLs. Field list is
/// the honest subset of a CSL `entry`: container covers journal,
/// publisher, or book series.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CitationSource {
    pub id: String,
    pub author: String,
    pub title: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub year: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub container: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub volume: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub issue: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub pages: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub doi: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub url: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub note: Option<String>,
}

/// One in-text citation: unique `id`, a live `at` anchor marking the
/// reference position, `source` naming a `sources[].id`, and an optional
/// `locator` string. The anchor has bookmark right gravity and never
/// drops — the same rules footnotes document.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Citation {
    pub id: String,
    pub at: CommentAnchor,
    pub source: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub locator: Option<String>,
}

/// Bibliography entry ordering. `"alpha"` sorts cached entries by their
/// formatted text (then source id); `"citation"` orders them by each
/// source's first citation in document order.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum BibliographySort {
    #[default]
    Alpha,
    Citation,
}

/// One cached bibliography entry: `source` is the source id (unique within
/// a field) and `text` the deterministic formatted line produced by
/// `format_source` at last scan.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BibliographyEntry {
    pub source: String,
    pub text: String,
}

/// A bibliography field's durable state: the entry ordering plus the
/// cached `entries` snapshot (regenerated by insert/update/refresh;
/// `listBibliography` is the live read).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BibliographyField {
    #[serde(default)]
    pub sort: BibliographySort,
    pub entries: Vec<BibliographyEntry>,
}

fn anchor_pos(a: &CommentAnchor) -> Pos {
    Pos {
        block: a.block,
        offset: a.offset,
    }
}

fn anchor_of(p: Pos) -> CommentAnchor {
    CommentAnchor {
        block: p.block,
        offset: p.offset,
    }
}

fn optional_text(v: Option<&Value>, name: &str) -> Result<Option<String>, EngineError> {
    match v {
        None | Some(Value::Null) => Ok(None),
        Some(v) => {
            let s = as_str(v, name)?;
            if s.chars().count() > SOURCE_TEXT_MAX {
                return Err(EngineError::validation(format!(
                    "{name} must be at most {SOURCE_TEXT_MAX} characters"
                )));
            }
            Ok(Some(s.to_string()))
        }
    }
}

fn validate_source_text(s: &str, name: &str, required: bool) -> Result<(), EngineError> {
    if required && s.trim().is_empty() {
        return Err(EngineError::validation(format!("source {name} must not be blank")));
    }
    if s.chars().count() > SOURCE_TEXT_MAX {
        return Err(EngineError::validation(format!(
            "source {name} must be at most {SOURCE_TEXT_MAX} characters"
        )));
    }
    Ok(())
}

/// Field-level source validation shared by ops and restore.
fn validate_source(s: &CitationSource) -> Result<(), EngineError> {
    validate_style_token(&s.id, "source id")?;
    validate_source_text(&s.author, "author", true)?;
    validate_source_text(&s.title, "title", true)?;
    for (value, name) in [
        (&s.year, "year"),
        (&s.container, "container"),
        (&s.volume, "volume"),
        (&s.issue, "issue"),
        (&s.pages, "pages"),
        (&s.doi, "doi"),
        (&s.url, "url"),
        (&s.note, "note"),
    ] {
        if let Some(v) = value {
            validate_source_text(v, name, false)?;
        }
    }
    Ok(())
}

/// Full source-list validation for restore: count and id uniqueness.
pub fn validate_sources(sources: &[CitationSource]) -> Result<(), EngineError> {
    if sources.len() > SOURCES_MAX {
        return Err(EngineError::validation("too many sources"));
    }
    let mut seen = std::collections::HashSet::with_capacity(sources.len());
    for s in sources {
        validate_source(s)?;
        if !seen.insert(s.id.as_str()) {
            return Err(EngineError::validation(format!(
                "duplicate source id '{}'",
                s.id
            )));
        }
    }
    Ok(())
}

/// Field-level citation validation shared by ops and restore: id token,
/// locator bound, in-range anchor on a text-bearing (non-table, non-toc,
/// non-bibliography) block, and `source` naming an existing source.
fn validate_citation(
    c: &Citation,
    sources: &[CitationSource],
    blocks: &[Block],
) -> Result<(), EngineError> {
    validate_style_token(&c.id, "citation id")?;
    if let Some(l) = &c.locator {
        if l.chars().count() > LOCATOR_MAX {
            return Err(EngineError::validation(format!(
                "citation locator must be at most {LOCATOR_MAX} characters"
            )));
        }
    }
    if !sources.iter().any(|s| s.id == c.source) {
        return Err(EngineError::validation(format!(
            "citation '{}' references unknown source '{}'",
            c.id, c.source
        )));
    }
    let Some(b) = blocks.get(c.at.block) else {
        return Err(EngineError::out_of_bounds(format!(
            "citation '{}' anchor block {} out of range ({} blocks)",
            c.id,
            c.at.block,
            blocks.len()
        )));
    };
    if matches!(
        b.kind,
        BlockKind::Table | BlockKind::Toc | BlockKind::Bibliography
    ) {
        return Err(EngineError::validation(format!(
            "citation '{}' anchor must not sit on a table, toc, or bibliography field block",
            c.id
        )));
    }
    if c.at.offset > block_len(b) {
        return Err(EngineError::out_of_bounds(format!(
            "citation '{}' anchor offset {} out of range (block {} has {} chars)",
            c.id,
            c.at.offset,
            c.at.block,
            block_len(b)
        )));
    }
    Ok(())
}

/// Full citation-list validation for restore: count, id uniqueness, and
/// every citation's fields/anchor/source against the final state. Runs
/// before live state is replaced; `validate_sources` must run first.
pub fn validate_citations(
    citations: &[Citation],
    sources: &[CitationSource],
    blocks: &[Block],
) -> Result<(), EngineError> {
    if citations.len() > CITATIONS_MAX {
        return Err(EngineError::validation("too many citations"));
    }
    let mut seen = std::collections::HashSet::with_capacity(citations.len());
    for c in citations {
        validate_citation(c, sources, blocks)?;
        if !seen.insert(c.id.as_str()) {
            return Err(EngineError::validation(format!(
                "duplicate citation id '{}'",
                c.id
            )));
        }
    }
    Ok(())
}

/// Sort key shared by `listCitations` numbering and output order.
fn citation_sort_key(c: &Citation) -> (usize, usize, &str) {
    (c.at.block, c.at.offset, c.id.as_str())
}

/// Deterministic plain-text rendering of one source — the only formatting
/// the engine does (no CSL). Segments: `Author. Title. Year. Container,
/// volume(issue), pages. doi:… url:… note.` Present optional fields join
/// in that fixed order; empty strings are skipped.
fn format_source(s: &CitationSource) -> String {
    let mut out = String::new();
    let mut push = |segment: &str| {
        if !segment.trim().is_empty() {
            if !out.is_empty() {
                out.push(' ');
            }
            out.push_str(segment.trim_end_matches([' ', '.']));
            out.push('.');
        }
    };
    push(&format!("{}.", s.author));
    push(&format!("{}.", s.title));
    if let Some(v) = &s.year {
        push(v);
    }
    // Container line: "Container, volume(issue), pages".
    let mut container = String::new();
    if let Some(v) = &s.container {
        container.push_str(v.trim());
    }
    if let Some(v) = &s.volume {
        if !container.is_empty() {
            container.push_str(", ");
        }
        container.push_str(v.trim());
    }
    if let Some(v) = &s.issue {
        if !container.is_empty() {
            container.push('(');
            container.push_str(v.trim());
            container.push(')');
        } else {
            container.push_str(v.trim());
        }
    }
    if let Some(v) = &s.pages {
        if !container.is_empty() {
            container.push_str(", ");
        }
        container.push_str(v.trim());
    }
    push(&container);
    if let Some(v) = &s.doi {
        push(&format!("doi:{}", v.trim()));
    }
    if let Some(v) = &s.url {
        push(v);
    }
    if let Some(v) = &s.note {
        push(v);
    }
    out
}

/// Live bibliography scan: every source cited at least once, in the
/// field's `sort` order, formatted by `format_source`. `citation` order
/// is first-citation document order; `alpha` is formatted-text order
/// (source id breaks ties). Deterministic — `listBibliography` always
/// agrees with what `refreshBibliography` would store.
fn scan_bibliography(
    citations: &[Citation],
    sources: &[CitationSource],
    sort: BibliographySort,
) -> Vec<BibliographyEntry> {
    // First-citation order: sort citations by anchor then id, keep the
    // first occurrence of each source id.
    let mut ordered: Vec<&Citation> = citations.iter().collect();
    ordered.sort_by(|a, b| citation_sort_key(a).cmp(&citation_sort_key(b)));
    let mut first_seen: Vec<&str> = Vec::new();
    for c in ordered {
        if !first_seen.contains(&c.source.as_str()) {
            first_seen.push(c.source.as_str());
        }
    }
    let mut entries: Vec<BibliographyEntry> = first_seen
        .iter()
        .filter_map(|id| {
            sources.iter().find(|s| s.id == *id).map(|s| BibliographyEntry {
                source: s.id.clone(),
                text: format_source(s),
            })
        })
        .collect();
    match sort {
        BibliographySort::Alpha => {
            entries.sort_by(|a, b| {
                a.text.cmp(&b.text).then_with(|| a.source.cmp(&b.source))
            });
        }
        BibliographySort::Citation => {
            // first_seen order is already first-citation document order.
        }
    }
    entries
}

/// Full bibliography-block validation for restore and staged candidates:
/// the `kind:"bibliography"` ⇔ payload invariant, field-block hygiene
/// (empty inlines, no list/style_id/table/format), the field-count
/// budget, and every cached entry (in-bounds text, unique `source` —
/// ordering itself is not enforceable without the live collections, so
/// `refreshBibliography`/`updateBibliography` own it). Runs before live
/// state is replaced.
pub fn validate_bibliography(blocks: &[Block]) -> Result<(), EngineError> {
    let mut fields = 0usize;
    for b in blocks {
        match (&b.kind, &b.bibliography) {
            (BlockKind::Bibliography, Some(f)) => {
                fields += 1;
                if fields > BIBLIOGRAPHY_FIELDS_MAX {
                    return Err(EngineError::validation("bibliography field limit reached"));
                }
                if !b.inlines.is_empty() {
                    return Err(EngineError::validation(
                        "bibliography blocks must not carry inlines",
                    ));
                }
                if b.list.is_some() {
                    return Err(EngineError::validation(
                        "bibliography blocks cannot be list members",
                    ));
                }
                if b.style_id.is_some() {
                    return Err(EngineError::validation(
                        "bibliography blocks cannot carry a style_id",
                    ));
                }
                if b.table.is_some() {
                    return Err(EngineError::validation(
                        "bibliography blocks cannot carry a table payload",
                    ));
                }
                if b.toc.is_some() {
                    return Err(EngineError::validation(
                        "bibliography blocks cannot carry a toc payload",
                    ));
                }
                if b.format.is_some() {
                    return Err(EngineError::validation(
                        "bibliography blocks cannot carry a paragraph format",
                    ));
                }
                if f.entries.len() > SOURCES_MAX {
                    return Err(EngineError::validation(
                        "bibliography entry count cannot exceed the source limit",
                    ));
                }
                let mut seen = std::collections::HashSet::with_capacity(f.entries.len());
                for e in &f.entries {
                    if e.text.chars().count() > BIBLIO_TEXT_MAX {
                        return Err(EngineError::validation(format!(
                            "bibliography entry text must be at most {BIBLIO_TEXT_MAX} characters"
                        )));
                    }
                    if !seen.insert(e.source.as_str()) {
                        return Err(EngineError::validation(
                            "bibliography entries must not repeat a source",
                        ));
                    }
                }
            }
            (BlockKind::Bibliography, None) => {
                return Err(EngineError::validation(
                    "bibliography block is missing its bibliography payload",
                ));
            }
            (_, Some(_)) => {
                return Err(EngineError::validation(
                    "non-bibliography block carries a bibliography payload",
                ));
            }
            _ => {}
        }
    }
    Ok(())
}

