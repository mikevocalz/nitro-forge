    #[test]
    fn bibliography_field_scan_sort_refresh_and_guards() {
        let mut e = cited_doc();
        apply(
            &mut e,
            "addCitation",
            json!({"at":{"block":0,"offset":4},"source":"src-1","locator":"p.1"}),
        );
        apply(
            &mut e,
            "addCitation",
            json!({"at":{"block":0,"offset":10},"source":"src-b"}),
        );
        let r = apply(&mut e, "insertBibliography", json!({"index":1}));
        assert_eq!(r.data["block_index"], 1);
        let d = apply(&mut e, "describe", json!({})).data;
        let field = &d["blocks"][1]["bibliography"];
        assert_eq!(field["sort"], "alpha");
        // Alpha order: "Ada Lovelace..." before "Grace Hopper...".
        let entries = field["entries"].as_array().unwrap();
        assert_eq!(entries.len(), 2);
        assert_eq!(entries[0]["source"], "src-1");
        assert!(entries[0]["text"].as_str().unwrap().contains("Ada Lovelace"));
        assert!(entries[0]["text"].as_str().unwrap().contains("Journal"));
        assert_eq!(entries[1]["source"], "src-b");

        // listBibliography honors the field's sort; bare defaults alpha.
        assert_eq!(apply(&mut e, "listBibliography", json!({"block":1})).data["count"], 2);
        // updateBibliography switches to citation order and rescans.
        apply(&mut e, "updateBibliography", json!({"block":1,"sort":"citation"}));
        let d = apply(&mut e, "describe", json!({})).data;
        let entries = d["blocks"][1]["bibliography"]["entries"].as_array().unwrap();
        assert_eq!(entries[0]["source"], "src-1");
        // Flip citation order: an earlier src-b citation moves it first.
        apply(
            &mut e,
            "addCitation",
            json!({"at":{"block":0,"offset":0},"source":"src-b"}),
        );
        apply(&mut e, "refreshBibliography", json!({"block":1}));
        let d = apply(&mut e, "describe", json!({})).data;
        let entries = d["blocks"][1]["bibliography"]["entries"].as_array().unwrap();
        assert_eq!(entries[0]["source"], "src-b");
        assert_eq!(entries[1]["source"], "src-1");
        // listBibliography {block} agrees with the cache.
        let live = apply(&mut e, "listBibliography", json!({"block":1})).data;
        assert_eq!(live["entries"][0]["source"], "src-b");
        // Eventless refresh when nothing changed.
        let noop = apply(&mut e, "refreshBibliography", json!({"block":1}));
        assert!(noop.events.is_empty());

        // Guards: field blocks reject text ops like toc blocks.
        let before = e.snapshot().unwrap();
        for (op, payload) in [
            ("insertText", json!({"at":{"block":1,"offset":0},"text":"x"})),
            ("splitBlock", json!({"at":{"block":1,"offset":0}})),
            ("mergeBlock", json!({"index":1})),
            ("setBlockStyle", json!({"block":1,"style_id":null})),
            ("setParagraphFormat", json!({"block":1,"alignment":"center"})),
            (
                "deleteRange",
                json!({"from":{"block":1,"offset":0},"to":{"block":2,"offset":0}}),
            ),
        ] {
            assert!(e.apply(Command::new(op, payload)).is_err(), "{op} accepted");
            assert_eq!(e.snapshot().unwrap(), before, "{op} mutated state");
        }
        // setBlockKind converts the field to a paragraph, dropping payload.
        apply(&mut e, "setBlockKind", json!({"block":1,"kind":"para"}));
        let d = apply(&mut e, "describe", json!({})).data;
        assert!(d["blocks"][1].get("bibliography").is_none());
        assert!(e.apply(Command::new("exportDocx", json!({}))).is_ok());
    }

