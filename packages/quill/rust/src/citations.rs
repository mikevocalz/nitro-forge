    #[test]
    fn snapshot_round_trip_and_hostile_restore() {
        let mut e = cited_doc();
        apply(
            &mut e,
            "addCitation",
            json!({"at":{"block":0,"offset":4},"source":"src-1","locator":"p.9"}),
        );
        apply(&mut e, "insertBibliography", json!({"index":1}));
        let bytes = e.snapshot().unwrap();
        let payload = decode_envelope(&bytes).unwrap().1;
        let v: Value = serde_json::from_slice(payload).unwrap();
        // citations/sources ride the schema:3 document; bibliography rides blocks.
        assert_eq!(v["schema"], 3);
        assert_eq!(v["document"]["citations"].as_array().unwrap().len(), 1);
        assert_eq!(v["document"]["sources"].as_array().unwrap().len(), 2);
        assert_eq!(v["document"]["blocks"][1]["kind"], "bibliography");
        let mut re = engine();
        re.restore(&bytes).unwrap();
        assert_eq!(citations(&mut re)["citations"].as_array().unwrap().len(), 1);
        assert_eq!(
            apply(&mut re, "listBibliography", json!({})).data["count"],
            1
        );

        // Hostile schema:3 payloads reject.
        let base = |document: Value| {
            json!({"kind":"quill","schema":3,"document":document})
        };
        let para = json!({"kind":"para","inlines":[{"text":"x","style":{}}]});
        let src = json!({"id":"s1","author":"a","title":"t"});
        let cit = |source: &str| {
            json!({"id":"c1","at":{"block":0,"offset":0},"source":source})
        };
        let cases = [
            // citation references a missing source
            base(json!({"blocks":[para.clone()],"bookmarks":[],"citations":[cit("ghost")],"sources":[src.clone()]})),
            // duplicate source ids
            base(json!({"blocks":[para.clone()],"bookmarks":[],"sources":[src.clone(),src.clone()]})),
            // blank author
            base(json!({"blocks":[para.clone()],"bookmarks":[],"sources":[{"id":"s","author":" ","title":"t"}]})),
            // citation anchor out of range
            base(json!({"blocks":[para.clone()],"bookmarks":[],"citations":[{"id":"c","at":{"block":9,"offset":0},"source":"s1"}],"sources":[src.clone()]})),
            // duplicate citation ids
            base(json!({"blocks":[para.clone()],"bookmarks":[],"citations":[cit("s1"),cit("s1")],"sources":[src.clone()]})),
            // bibliography kind without payload / payload on para
            base(json!({"blocks":[{"kind":"bibliography","inlines":[]}],"bookmarks":[]})),
            base(json!({"blocks":[{"kind":"para","inlines":[],"bibliography":{"sort":"alpha","entries":[]}}],"bookmarks":[]})),
            // bibliography entries repeating a source
            base(json!({"blocks":[{"kind":"bibliography","inlines":[],"bibliography":{"sort":"alpha","entries":[{"source":"s","text":"a"},{"source":"s","text":"b"}]}}],"bookmarks":[]})),
        ];
        for doc in cases {
            let mut e3 = engine();
            assert!(
                e3.restore(&encode_envelope(&serde_json::to_vec(&doc).unwrap()))
                    .is_err(),
                "hostile payload accepted: {doc}"
            );
        }
        // schema:2 and legacy payloads carrying the new keys reject.
        let legacy = json!({"blocks":[para],"citations":[],"sources":[]});
        let mut e2 = engine();
        assert!(e2
            .restore(&encode_envelope(&serde_json::to_vec(&legacy).unwrap()))
            .is_err());
    }

    #[test]
    fn new_import_batch_and_undo_redo() {
        let mut e = cited_doc();
        apply(
            &mut e,
            "addCitation",
            json!({"at":{"block":0,"offset":4},"source":"src-1"}),
        );
        apply(&mut e, "insertBibliography", json!({"index":1}));
        let snap = e.snapshot().unwrap();
        // Batch of source+citation ops is one undo entry.
        e.apply(Command::new(
            "__batch",
            json!({"commands":[
                {"op":"addSource","payload":{"author":"K","title":"T"}},
                {"op":"addCitation","payload":{"at":{"block":0,"offset":0},"source":"src-2"}}
            ]}),
        ))
        .unwrap();
        assert_eq!(citations(&mut e)["citations"].as_array().unwrap().len(), 2);
        assert!(e.undo().unwrap());
        assert_eq!(citations(&mut e)["citations"].as_array().unwrap().len(), 1);
        assert!(e.redo().unwrap());
        assert_eq!(citations(&mut e)["citations"].as_array().unwrap().len(), 2);
        // new clears everything.
        apply(&mut e, "new", json!({}));
        assert_eq!(citations(&mut e)["citations"].as_array().unwrap().len(), 0);
        assert_eq!(apply(&mut e, "listSources", json!({})).data["sources"]
            .as_array()
            .unwrap()
            .len(), 0);
        let _ = snap;
    }
