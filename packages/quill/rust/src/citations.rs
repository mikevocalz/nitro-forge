impl QuillEngine {
    fn find_source(&self, id: &str) -> Result<usize, EngineError> {
        self.sources
            .iter()
            .position(|s| s.id == id)
            .ok_or_else(|| EngineError::validation(format!("unknown source '{id}'")))
    }

    fn find_citation(&self, id: &str) -> Result<usize, EngineError> {
        self.citations
            .iter()
            .position(|c| c.id == id)
            .ok_or_else(|| EngineError::validation(format!("unknown citation '{id}'")))
    }

    /// Parse the optional source-metadata fields shared by `addSource` and
    /// `updateSource`. Absent keys keep `current`; explicit null clears.
    fn parse_source_fields(
        p: &Value,
        current: Option<&CitationSource>,
    ) -> Result<CitationSource, EngineError> {
        let base = current.cloned().unwrap_or(CitationSource {
            id: String::new(),
            author: String::new(),
            title: String::new(),
            year: None,
            container: None,
            volume: None,
            issue: None,
            pages: None,
            doi: None,
            url: None,
            note: None,
        });
        let mut s = base;
        for (key, slot) in [
            ("year", &mut s.year),
            ("container", &mut s.container),
            ("volume", &mut s.volume),
            ("issue", &mut s.issue),
            ("pages", &mut s.pages),
            ("doi", &mut s.doi),
            ("url", &mut s.url),
            ("note", &mut s.note),
        ] {
            if let Some(v) = p.get(key) {
                *slot = optional_text(Some(v), key)?;
            }
        }
        Ok(s)
    }

    /// `addSource {author,title,year?,container?,volume?,issue?,pages?,
    /// doi?,url?,note?,id?}` — defines one bibliography source. `author`
    /// and `title` are required non-blank text ≤512 chars; every optional
    /// field is a raw string ≤512 chars (never parsed — no DOI/URL
    /// fetching, no CSL). `id` is an optional unique token, else the
    /// engine assigns the smallest unused `src-N`. At most 1024 sources.
    pub(super) fn op_add_source(&mut self, p: &Value) -> Result<CommandResult, EngineError> {
        let id = match p.get("id") {
            Some(v) if v.is_null() => None,
            Some(v) => Some(as_str(v, "id")?.to_string()),
            None => None,
        };
        let mut source = Self::parse_source_fields(p, None)?;
        source.author = as_str(field(p, "author")?, "author")?.to_string();
        source.title = as_str(field(p, "title")?, "title")?.to_string();
        source.id = match id {
            Some(id) => {
                validate_style_token(&id, "source id")?;
                if self.sources.iter().any(|s| s.id == id) {
                    return Err(EngineError::validation(format!(
                        "source '{id}' already exists"
                    )));
                }
                id
            }
            None => (1..)
                .map(|i| format!("src-{i}"))
                .find(|candidate| !self.sources.iter().any(|s| s.id == *candidate))
                .expect("source id space exhausted below SOURCES_MAX"),
        };
        validate_source(&source)?;
        if self.sources.len() >= SOURCES_MAX {
            return Err(EngineError::validation("source limit reached"));
        }
        let id = source.id.clone();
        let before = self.sources.clone();
        self.sources.push(source);
        self.record_undo(
            0,
            Vec::new(),
            Vec::new(),
            Collections {
                sources: Some(before),
                ..Default::default()
            },
        );
        Ok(CommandResult::data(json!({ "ok": true, "id": id })))
    }

    /// `updateSource {id, author?, title?, year?, container?, volume?,
    /// issue?, pages?, doi?, url?, note?}` — patches the named fields;
    /// explicit null clears an optional field (author/title reject null
    /// and blank). Absent keys keep their values; no effective change is
    /// eventless. Changing a source does not rewrite cached bibliography
    /// entries — `refreshBibliography`/`updateBibliography` regenerate.
    pub(super) fn op_update_source(&mut self, p: &Value) -> Result<CommandResult, EngineError> {
        let id = as_str(field(p, "id")?, "id")?;
        let index = self.find_source(id)?;
        let mut updated = self.sources[index].clone();
        for (key, required) in [
            ("author", true),
            ("title", true),
        ] {
            if let Some(v) = p.get(key) {
                if v.is_null() {
                    return Err(EngineError::validation(format!(
                        "source {key} must not be null"
                    )));
                }
                let s = as_str(v, key)?;
                validate_source_text(s, key, required)?;
                if key == "author" {
                    updated.author = s.to_string();
                } else {
                    updated.title = s.to_string();
                }
            }
        }
        updated = Self::parse_source_fields(p, Some(&updated))?;
        // parse_source_fields carried author/title through unchanged;
        // re-apply in case the patch touched them (it did not — the loop
        // above owns those keys and parse_source_fields skips them).
        validate_source(&updated)?;
        if updated == self.sources[index] {
            return Ok(Self::read_only(json!({ "ok": true, "id": id })));
        }
        let before = self.sources.clone();
        self.sources[index] = updated;
        self.record_undo(
            0,
            Vec::new(),
            Vec::new(),
            Collections {
                sources: Some(before),
                ..Default::default()
            },
        );
        Ok(CommandResult::data(json!({ "ok": true, "id": id })))
    }

    /// `removeSource {id}` — deletes the source AND every citation that
    /// referenced it (the Word "delete source" cascade), as one undo
    /// entry. Cached bibliography entries are field data and simply go
    /// stale until the next refresh. Unknown ids reject.
    pub(super) fn op_remove_source(&mut self, p: &Value) -> Result<CommandResult, EngineError> {
        let id = as_str(field(p, "id")?, "id")?;
        self.find_source(id)?;
        let sources_before = self.sources.clone();
        let citations_before = self.citations.clone();
        self.sources.retain(|s| s.id != id);
        self.citations.retain(|c| c.source != id);
        self.record_undo(
            0,
            Vec::new(),
            Vec::new(),
            Collections {
                sources: Some(sources_before),
                citations: Some(citations_before),
                ..Default::default()
            },
        );
        Ok(CommandResult::data(json!({ "ok": true, "id": id })))
    }

    /// `listSources` — read-only; sorted by id, each entry carrying the
    /// stored fields plus `cited` (how many citations reference it).
    pub(super) fn op_list_sources(&self) -> Result<CommandResult, EngineError> {
        let mut sorted: Vec<&CitationSource> = self.sources.iter().collect();
        sorted.sort_by(|a, b| a.id.cmp(&b.id));
        let arr: Vec<Value> = sorted
            .iter()
            .map(|s| {
                let cited = self.citations.iter().filter(|c| c.source == s.id).count();
                let mut v = serde_json::to_value(s)?;
                v["cited"] = json!(cited);
                Ok(v)
            })
            .collect::<Result<Vec<_>, EngineError>>()?;
        Ok(Self::read_only(json!({ "sources": arr })))
    }

    /// `addCitation {at|pos|anchor, source, locator?, id?}` — anchors an
    /// in-text citation reference at `at` naming an existing `source`.
    /// `locator` is optional free text ≤128 chars (a page/section pin).
    /// `id` is an optional unique token — absent, the engine assigns the
    /// smallest unused `cit-N`. At most 2048 citations. Anchors on table,
    /// toc, or bibliography field blocks reject.
    pub(super) fn op_add_citation(&mut self, p: &Value) -> Result<CommandResult, EngineError> {
        let at = bookmark_pos(p)?;
        self.check_pos(at)?;
        if matches!(
            self.blocks[at.block].kind,
            BlockKind::Table | BlockKind::Toc | BlockKind::Bibliography
        ) {
            return Err(EngineError::validation(
                "cannot anchor a citation on a table or field block",
            ));
        }
        let source = as_str(field(p, "source")?, "source")?.to_string();
        self.find_source(&source)?;
        let locator = match p.get("locator") {
            Some(v) if v.is_null() => None,
            Some(v) => {
                let s = as_str(v, "locator")?;
                if s.chars().count() > LOCATOR_MAX {
                    return Err(EngineError::validation(format!(
                        "citation locator must be at most {LOCATOR_MAX} characters"
                    )));
                }
                Some(s.to_string())
            }
            None => None,
        };
        let id = match p.get("id") {
            Some(v) if v.is_null() => None,
            Some(v) => Some(as_str(v, "id")?.to_string()),
            None => None,
        };
        let id = match id {
            Some(id) => {
                validate_style_token(&id, "citation id")?;
                if self.citations.iter().any(|c| c.id == id) {
                    return Err(EngineError::validation(format!(
                        "citation '{id}' already exists"
                    )));
                }
                id
            }
            None => (1..)
                .map(|i| format!("cit-{i}"))
                .find(|candidate| !self.citations.iter().any(|c| c.id == *candidate))
                .expect("citation id space exhausted below CITATIONS_MAX"),
        };
        let citation = Citation {
            id: id.clone(),
            at: anchor_of(at),
            source,
            locator,
        };
        validate_citation(&citation, &self.sources, &self.blocks)?;
        if self.citations.len() >= CITATIONS_MAX {
            return Err(EngineError::validation("citation limit reached"));
        }
        let before = self.citations.clone();
        self.citations.push(citation);
        self.record_undo(
            0,
            Vec::new(),
            Vec::new(),
            Collections {
                citations: Some(before),
                ..Default::default()
            },
        );
        Ok(CommandResult::data(json!({ "ok": true, "id": id })))
    }

    /// `updateCitation {id, source?, locator?}` — re-points `source` to
    /// another existing source and/or patches `locator` (`null` clears).
    /// Absent fields keep their values; the anchor is not re-pointable.
    /// No effective change → eventless.
    pub(super) fn op_update_citation(&mut self, p: &Value) -> Result<CommandResult, EngineError> {
        let id = as_str(field(p, "id")?, "id")?;
        let index = self.find_citation(id)?;
        let mut updated = self.citations[index].clone();
        let mut touched = false;
        if let Some(v) = p.get("source") {
            touched = true;
            if v.is_null() {
                return Err(EngineError::validation("citation source must not be null"));
            }
            let source = as_str(v, "source")?;
            self.find_source(source)?;
            updated.source = source.to_string();
        }
        if let Some(v) = p.get("locator") {
            touched = true;
            updated.locator = if v.is_null() {
                None
            } else {
                let s = as_str(v, "locator")?;
                if s.chars().count() > LOCATOR_MAX {
                    return Err(EngineError::validation(format!(
                        "citation locator must be at most {LOCATOR_MAX} characters"
                    )));
                }
                Some(s.to_string())
            };
        }
        if !touched {
            return Ok(Self::read_only(json!({ "ok": true, "id": id })));
        }
        validate_citation(&updated, &self.sources, &self.blocks)?;
        if updated == self.citations[index] {
            return Ok(Self::read_only(json!({ "ok": true, "id": id })));
        }
        let before = self.citations.clone();
        self.citations[index] = updated;
        self.record_undo(
            0,
            Vec::new(),
            Vec::new(),
            Collections {
                citations: Some(before),
                ..Default::default()
            },
        );
        Ok(CommandResult::data(json!({ "ok": true, "id": id })))
    }

    /// `removeCitation {id}` — deletes the citation record; the anchor
    /// mark disappears with it (citation marks are records, not inline
    /// text). Unknown ids reject.
    pub(super) fn op_remove_citation(&mut self, p: &Value) -> Result<CommandResult, EngineError> {
        let id = as_str(field(p, "id")?, "id")?;
        let index = self.find_citation(id)?;
        let before = self.citations.clone();
        self.citations.remove(index);
        self.record_undo(
            0,
            Vec::new(),
            Vec::new(),
            Collections {
                citations: Some(before),
                ..Default::default()
            },
        );
        Ok(CommandResult::data(json!({ "ok": true, "id": id })))
    }

    /// `listCitations` — read-only; sorted by anchor position then id,
    /// each entry carrying its resolved 1-based `number` in document
    /// order plus the referenced `source` id and optional `locator`.
    pub(super) fn op_list_citations(&self) -> Result<CommandResult, EngineError> {
        let mut sorted: Vec<&Citation> = self.citations.iter().collect();
        sorted.sort_by(|a, b| citation_sort_key(a).cmp(&citation_sort_key(b)));
        let arr: Vec<Value> = sorted
            .iter()
            .enumerate()
            .map(|(i, c)| {
                let mut v = json!({
                    "id": c.id,
                    "at": { "block": c.at.block, "offset": c.at.offset },
                    "source": c.source,
                    "number": i + 1,
                });
                if let Some(l) = &c.locator {
                    v["locator"] = json!(l);
                }
                v
            })
            .collect();
        Ok(Self::read_only(json!({ "citations": arr })))
    }

    /// Index of the bibliography block at payload `block`, or a
    /// validation error.
    fn bibliography_block_index(&self, p: &Value) -> Result<usize, EngineError> {
        let index = as_usize(field(p, "block")?, "block")?;
        match self.blocks.get(index) {
            Some(b) if b.kind == BlockKind::Bibliography => Ok(index),
            Some(_) => Err(EngineError::validation(format!(
                "block {index} is not a bibliography field"
            ))),
            None => Err(EngineError::out_of_bounds(format!(
                "block {index} out of range ({} blocks)",
                self.blocks.len()
            ))),
        }
    }

    fn parse_bibliography_sort(v: Option<&Value>) -> Result<BibliographySort, EngineError> {
        match v {
            None | Some(Value::Null) => Ok(BibliographySort::default()),
            Some(v) => match as_str(v, "sort")? {
                "alpha" => Ok(BibliographySort::Alpha),
                "citation" => Ok(BibliographySort::Citation),
                other => Err(EngineError::validation(format!(
                    "unknown bibliography sort '{other}' (expected \"alpha\" or \"citation\")"
                ))),
            },
        }
    }

    /// `insertBibliography {index, sort?}` — inserts one
    /// `kind:"bibliography"` field block at `index` (0..=block count) and
    /// populates its cached entries from a live scan of the cited
    /// sources. `sort` is `"alpha"` (default) or `"citation"`. Anchor
    /// remapping is identical to `insertBlock` for every collection;
    /// bibliography entries reference source ids, never block indices,
    /// so no field payload remaps.
    pub(super) fn op_insert_bibliography(
        &mut self,
        p: &Value,
    ) -> Result<CommandResult, EngineError> {
        let index = as_usize(field(p, "index")?, "index")?;
        let sort = Self::parse_bibliography_sort(p.get("sort"))?;
        if index > self.blocks.len() {
            return Err(EngineError::out_of_bounds(format!(
                "index {index} out of range ({} blocks)",
                self.blocks.len()
            )));
        }
        if self
            .blocks
            .iter()
            .filter(|b| b.kind == BlockKind::Bibliography)
            .count()
            >= BIBLIOGRAPHY_FIELDS_MAX
        {
            return Err(EngineError::validation("bibliography field limit reached"));
        }
        let field = BibliographyField {
            sort,
            entries: Vec::new(),
        };
        let mut next = self.blocks.clone();
        next.insert(
            index,
            Block {
                kind: BlockKind::Bibliography,
                list: None,
                style_id: None,
                inlines: Vec::new(),
                table: None,
                toc: None,
                bibliography: Some(field),
                format: None,
            },
        );
        lists::validate(&next)?;
        validate_bibliography(&next)?;
        let old = std::mem::replace(&mut self.blocks, next);
        let bookmarks_before = self.bookmarks.clone();
        let comments_before = self.comments.clone();
        let sections_before = self.sections.clone();
        let revisions_before = self.revisions.clone();
        let footnotes_before = self.footnotes.clone();
        let citations_before = self.citations.clone();
        self.remap_bookmarks_insert_block(index);
        self.remap_comments_insert_block(index);
        self.remap_sections_insert_block(index);
        self.remap_revisions_insert_block(index);
        self.remap_footnotes_insert_block(index);
        self.remap_citations_insert_block(index);
        self.remap_toc_insert_block(index);
        // Scan after the splice + remaps so citation anchors are final;
        // the new field's own entries need no remap (source ids only).
        let entries = scan_bibliography(&self.citations, &self.sources, sort);
        self.blocks[index]
            .bibliography
            .as_mut()
            .expect("just inserted a bibliography block")
            .entries = entries;
        self.record_undo(
            0,
            old,
            self.blocks.clone(),
            Collections::anchors(
                bookmarks_before,
                comments_before,
                sections_before,
                revisions_before,
                footnotes_before,
                citations_before,
            ),
        );
        Ok(CommandResult::data(json!({ "ok": true, "block_index": index })))
    }

    /// `updateBibliography {block, sort?}` — repoints the field's entry
    /// ordering (absent keeps it) and rescans entries, so a reconfigured
    /// field never shows entries in the wrong order. No effective change
    /// → eventless.
    pub(super) fn op_update_bibliography(
        &mut self,
        p: &Value,
    ) -> Result<CommandResult, EngineError> {
        let index = self.bibliography_block_index(p)?;
        let current = self
            .blocks[index]
            .bibliography
            .clone()
            .expect("bibliography block checked");
        // Absent or null `sort` keeps the current ordering; a present
        // value must name a known sort.
        let sort = match p.get("sort") {
            None | Some(Value::Null) => current.sort,
            Some(v) => match as_str(v, "sort")? {
                "alpha" => BibliographySort::Alpha,
                "citation" => BibliographySort::Citation,
                other => {
                    return Err(EngineError::validation(format!(
                        "unknown bibliography sort '{other}' (expected \"alpha\" or \"citation\")"
                    )))
                }
            },
        };
        let field = BibliographyField {
            sort,
            entries: scan_bibliography(&self.citations, &self.sources, sort),
        };
        let mut new_block = self.blocks[index].clone();
        new_block.bibliography = Some(field.clone());
        if new_block == self.blocks[index] {
            return Ok(Self::read_only(json!({ "ok": true, "block": index })));
        }
        let old = std::mem::replace(&mut self.blocks[index], new_block.clone());
        self.record_undo(index, vec![old], vec![new_block], Collections::default());
        Ok(CommandResult::data(json!({ "ok": true, "block": index })))
    }

    /// `refreshBibliography {block}` — rescans the field's cached entries
    /// from the live citations/sources (the Word "update field"
    /// gesture). Identical result → eventless.
    pub(super) fn op_refresh_bibliography(
        &mut self,
        p: &Value,
    ) -> Result<CommandResult, EngineError> {
        let index = self.bibliography_block_index(p)?;
        let current = self
            .blocks[index]
            .bibliography
            .clone()
            .expect("bibliography block checked");
        let entries = scan_bibliography(&self.citations, &self.sources, current.sort);
        if entries == current.entries {
            return Ok(Self::read_only(json!({ "ok": true, "block": index })));
        }
        let mut new_block = self.blocks[index].clone();
        new_block
            .bibliography
            .as_mut()
            .expect("bibliography block checked")
            .entries = entries;
        let old = std::mem::replace(&mut self.blocks[index], new_block.clone());
        if let Err(e) = validate_bibliography(&self.blocks) {
            self.blocks[index] = old;
            return Err(e);
        }
        self.record_undo(index, vec![old], vec![new_block], Collections::default());
        Ok(CommandResult::data(json!({ "ok": true, "block": index })))
    }

    /// `listBibliography {block?}` — read-only live scan, always current
    /// (never the cache). With `block` naming a bibliography field the
    /// scan honors that field's `sort`; without it entries sort `"alpha"`.
    /// Only cited sources appear.
    pub(super) fn op_list_bibliography(&self, p: &Value) -> Result<CommandResult, EngineError> {
        let sort = match p.get("block") {
            Some(v) if !v.is_null() => {
                let index = as_usize(v, "block")?;
                match self.blocks.get(index) {
                    Some(b) if b.kind == BlockKind::Bibliography => {
                        self.blocks[index]
                            .bibliography
                            .as_ref()
                            .expect("bibliography block carries payload")
                            .sort
                    }
                    Some(_) => {
                        return Err(EngineError::validation(format!(
                            "block {index} is not a bibliography field"
                        )))
                    }
                    None => {
                        return Err(EngineError::out_of_bounds(format!(
                            "block {index} out of range ({} blocks)",
                            self.blocks.len()
                        )))
                    }
                }
            }
            _ => BibliographySort::Alpha,
        };
        let entries = scan_bibliography(&self.citations, &self.sources, sort);
        let count = entries.len();
        Ok(Self::read_only(json!({
            "entries": entries.iter().map(|e| json!({
                "source": e.source,
                "text": e.text,
            })).collect::<Vec<_>>(),
            "count": count,
        })))
    }

    // -- citation anchor remapping -------------------------------------------
    //
    // The `at` anchor is a single right-gravity mark with bookmark
    // semantics — identical to footnotes: `map_pos_insert`/`map_pos_split`
    // with `left = false`, `map_pos_delete` clamps like a comment endpoint
    // and never drops. `replaceText` re-anchors through per-block match
    // spans; `changeCase` maps through the per-scalar offset table (see
    // change_case.rs).

    /// `insertText` at `at` inserting `text` (already validated).
    pub(super) fn remap_citations_insert_text(&mut self, at: Pos, text: &str) {
        if self.citations.is_empty() {
            return;
        }
        let added = text.bytes().filter(|&b| b == b'\n').count();
        let plain = text.chars().count();
        let last_len = text.rsplit('\n').next().map_or(0, |s| s.chars().count());
        for c in &mut self.citations {
            c.at = anchor_of(Self::map_pos_insert(
                anchor_pos(&c.at),
                at,
                added,
                last_len,
                plain,
                false,
            ));
        }
    }

    /// `deleteRange` from `from` to `to` (already validated, from != to).
    /// Anchors inside the deleted span clamp to `from` — the citation
    /// survives rather than dropping silently.
    pub(super) fn remap_citations_delete(&mut self, from: Pos, to: Pos) {
        if self.citations.is_empty() {
            return;
        }
        for c in &mut self.citations {
            c.at = anchor_of(Self::map_pos_delete(anchor_pos(&c.at), from, to));
        }
    }

    /// `splitBlock` at `at`: a mark at the split point moves to the tail
    /// block's start (right gravity, same as a bookmark).
    pub(super) fn remap_citations_split(&mut self, at: Pos) {
        if self.citations.is_empty() {
            return;
        }
        for c in &mut self.citations {
            c.at = anchor_of(Self::map_pos_split(anchor_pos(&c.at), at, false));
        }
    }

    /// `mergeBlock` at `index` (same mapping as bookmarks).
    pub(super) fn remap_citations_merge(&mut self, index: usize, head_len: usize) {
        if self.citations.is_empty() {
            return;
        }
        for c in &mut self.citations {
            c.at = anchor_of(Self::map_pos_merge(anchor_pos(&c.at), index, head_len));
        }
    }

    /// `insertBlock`/`insertTable`/`insertToc`/`insertBibliography` at
    /// `index`: anchors at or after it shift one block.
    pub(super) fn remap_citations_insert_block(&mut self, index: usize) {
        if self.citations.is_empty() {
            return;
        }
        for c in &mut self.citations {
            if c.at.block >= index {
                c.at.block += 1;
            }
        }
    }

    /// `replaceText` re-anchoring through one block's `(start,end)` match
    /// spans — bookmark right gravity via `remap_offset_through_matches`.
    pub(super) fn remap_citations_replace_block(
        citations: &mut [Citation],
        block: usize,
        span: &[(usize, usize)],
        repl_len: usize,
    ) {
        for c in citations.iter_mut() {
            if c.at.block == block {
                c.at.offset = remap_offset_through_matches(c.at.offset, span, repl_len);
            }
        }
    }
}

