import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { skiaWebAssets } from './skia-web-assets.mjs';
const manifest = fileURLToPath(new URL('./package.json', import.meta.url));
const skiaRequire = createRequire(createRequire(manifest).resolve('react-native-skia/package.json'));
assert.equal(skiaRequire('./package.json').version, '3.9.1');
const expected = await readFile(skiaRequire.resolve('canvaskit-wasm/bin/full/canvaskit.wasm'));
assert.deepEqual([...expected.subarray(0, 4)], [0, 97, 115, 109]);
const plugin = skiaWebAssets(manifest);
let middleware;
plugin.configResolved({ base: '/preview/' });
plugin.configureServer({ middlewares: { use(fn) { middleware = fn; } }, config: { logger: { error() {} } } });
async function request(method, url) {
  const result = { statusCode: 200, headers: {}, body: null, next: false };
  await middleware({ method, url }, { set statusCode(value) { result.statusCode = value; }, setHeader(key, value) { result.headers[key] = value; }, end(body) { result.body = body; } }, () => { result.next = true; });
  return result;
}
const get = await request('GET', '/preview/canvaskit/canvaskit.wasm?v=1');
assert.equal(get.headers['Content-Type'], 'application/wasm');
assert.deepEqual(get.body, expected);
assert.equal((await request('HEAD', '/preview/canvaskit/canvaskit.wasm')).body, undefined);
assert.equal((await request('POST', '/preview/canvaskit/canvaskit.wasm')).statusCode, 405);
assert.equal((await request('GET', '/preview/canvaskit/../../package.json')).next, true);
assert.equal((await request('GET', '/canvaskit/canvaskit.wasm')).next, true);
let emitted;
await plugin.generateBundle.call({ emitFile(asset) { emitted = asset; } });
assert.equal(emitted.fileName, 'canvaskit/canvaskit.wasm');
assert.deepEqual(emitted.source, expected);
console.log(`PASS: canonical CanvasKit ${expected.length} bytes, GET/HEAD/method/path guards and production emission`);
